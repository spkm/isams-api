<?php

namespace spkm\IsamsApi\Generator;

use Illuminate\Support\Str;
use Nette\PhpGenerator\Method;
use Nette\PhpGenerator\Parameter;

/**
 * ENDPOINTS.md: every REST resource call, written as a caller writes it, with what it returns, one table per area; then
 * the Batch API's calls, the root nodes no method fills, and the photo feeds.
 *
 * @phpstan-import-type BatchGroup from BatchGenerator
 */
final class EndpointsDocument
{
    /**
     * @param  array{areas: list<string>, children: array<string, array<string, string>>, calls: array<string, list<Method>>}  $rest  the areas' resource classes, their child resources and their methods
     * @param  array{groups: array<string, BatchGroup>, unnamed: list<array{module: string, root: string, model: string}>}  $batch  the Batch API's groups and the root nodes no method fills
     */
    public function render(array $rest, array $batch): string
    {
        $contents = [];
        $sections = [];
        $total = 0;

        foreach ($rest['areas'] as $area) {
            $name = lcfirst((string) preg_replace('/Resource$/', '', class_basename($area)));
            $title = Str::headline($name);
            $rows = [];

            foreach ($this->chains($area, "Isams::$name()", $rest['children']) as $resource => $chain) {
                foreach ($rest['calls'][$resource] ?? [] as $method) {
                    $call = $chain.'->'.$method->getName().'('.implode(', ', array_map($this->parameter(...), $method->getParameters())).')';
                    $rows[] = '| `'.str_replace('|', '\\|', $call).'` | '.str_replace('|', '\\|', $this->returns($method)).' |';
                }
            }

            sort($rows);
            $total += count($rows);
            $contents[] = '  - ['.$title.'](#'.Str::slug($title).') ('.count($rows).')';
            $sections[] = "### $title\n\n| Call | Returns |\n|---|---|\n".implode("\n", $rows)."\n";
        }

        ['contents' => $batchContents, 'section' => $batchSection] = $this->batch($batch);

        return implode("\n", [
            '# Endpoints',
            '',
            '<!-- Generated by bin/generate from the iSAMS API spec and generator/batch/nodes.php: edit those, not this file. -->',
            '',
            'Everything the package can ask iSAMS for, as you write it: the REST API\'s calls, then the Batch API\'s methods.',
            '',
            '- [REST API](#rest-api) ('.number_format($total).' calls)',
            ...$contents,
            ...$batchContents,
            '',
            '## REST API',
            '',
            'Each call is a resource method and returns what iSAMS sent back. Lists come back as a `Collection` of models, and',
            'lists iSAMS sends in pages as a `LazyCollection` that fetches each page as you loop. Writes iSAMS answers without a',
            'body return `true` (`bool`), as Eloquent\'s `update()` and `delete()` do. A failure never returns `false`: it',
            'throws an `IsamsApiException`. See [Two ways to call iSAMS](README.md#two-ways-to-call-isams) and',
            '[Errors](README.md#errors). Each call\'s docblock names the request it sends, for `Isams::send()`.',
            '',
            implode("\n", $sections),
            $batchSection,
        ]);
    }

    /**
     * The Batch API's part: a table per group, the root nodes no known method fills, and the photo feeds.
     *
     * @param  array{groups: array<string, BatchGroup>, unnamed: list<array{module: string, root: string, model: string}>}  $batch
     * @return array{contents: list<string>, section: string}
     */
    private function batch(array $batch): array
    {
        $contents = [];
        $sections = [];

        foreach ($batch['groups'] as $group => ['accessor' => $accessor, 'calls' => $calls]) {
            $rows = array_map(fn (array $call) => '| `Isams::batch()->'.$accessor.'()->'.$call['name'].'('.implode(', ', array_map(fn (array $parameter) => $parameter['signature'], $call['parameters'])).')` | `LazyCollection<'.class_basename($call['model']).'>` |', $calls);
            sort($rows);
            $contents[] = "  - [$group](#batch-".strtolower($group).') ('.count($rows).')';
            $sections[] = "### Batch: $group\n\n| Call | Returns |\n|---|---|\n".implode("\n", $rows)."\n";
        }

        $unnamed = array_map(fn (array $root) => "| `Isams::batch()->send(new BatchRequest)->dto()->models('{$root['module']}', '{$root['root']}')` | `Collection<".class_basename($root['model']).'>` |', $batch['unnamed']);

        $section = implode("\n", [
            '## Batch API',
            '',
            'Each call runs one Batch API method and returns its records as a lazy collection of models, taking the method\'s filters as named',
            'parameters; a failure throws a `BatchApiException`. Pass a key\'s name to `Isams::batch()` to use a key other than the',
            'default. To run several methods in one request, send a `BatchRequest` and read each method from the response; see',
            '[Batch API](README.md#batch-api).',
            '',
            '```php',
            '$students = Isams::batch()->pupil()->currentPupils(); // LazyCollection<Pupil>',
            '',
            '// Mother and father contacts, at their work and company locations, of students with system status 0 or 1',
            '// who live at home and enrol in 2026 or 2027',
            '$contacts = Isams::batch()->contactAdvanced()->contacts(',
            '    contactTypes: [\'Mother\', \'Father\'],',
            '    contactLocations: [\'Work\', \'Company\'],',
            '    studentHome: true,',
            '    systemStatusesToInclude: [0, 1],',
            '    enrolmentSchoolYearsToInclude: [2026, 2027],',
            '); // LazyCollection<Contact>',
            '',
            '// Several methods in one request, each filtered under the names iSAMS documents for its filter',
            '$batch = Isams::batch()->send(new BatchRequest(',
            '    BatchFilters::make()',
            '        ->methods(\'Pupil_GetCurrentPupils\', \'Pupil_GetPassports\', \'ContactAdvanced_GetContacts\')',
            '        ->filter(\'StudentManager\', \'Passports\', [\'SystemStatusesToInclude\' => [0, 1]])',
            '        ->filter(\'StudentManager\', \'Contacts\', [',
            '            \'ContactTypes\' => [\'Mother\', \'Father\'],',
            '            \'StudentHome\' => true,',
            '            \'SystemStatusesToInclude\' => [0, 1],',
            '        ])',
            '))->dto();',
            '',
            '$students = $batch->method(\'Pupil_GetCurrentPupils\');',
            '$passports = $batch->method(\'Pupil_GetPassports\');',
            '$contacts = $batch->method(\'ContactAdvanced_GetContacts\');',
            '```',
            '',
            implode("\n", $sections),
            '### Batch: root nodes no method names',
            '',
            'These arrive when a request runs everything allocated to the key.',
            '',
            '| Call | Returns |',
            '|---|---|',
            implode("\n", $unnamed),
            '',
            '### Batch: photos',
            '',
            '| Call | Returns |',
            '|---|---|',
            '| `Isams::batch()->staffPhotos()` | `BatchPhotos`: `photos()` yields each staff id and PNG |',
            '| `Isams::batch()->studentPhotos()` | `BatchPhotos`: `photos()` yields each student id and PNG |',
            '',
        ]);

        return [
            'contents' => [
                '- [Batch API](#batch-api) ('.array_sum(array_map(fn (array $group) => count($group['calls']), $batch['groups'])).' calls)',
                ...$contents,
                '  - [Root nodes no method names](#batch-root-nodes-no-method-names) ('.count($unnamed).')',
                '  - [Photos](#batch-photos) (2)',
            ],
            'section' => $section,
        ];
    }

    /**
     * The call that reaches a resource and each of its child resources, as a caller writes it, keyed by resource class.
     *
     * @param  array<string, array<string, string>>  $children  resource class => accessor => child resource class
     * @return array<string, string>
     */
    private function chains(string $resource, string $chain, array $children): array
    {
        $chains = [$resource => $chain];

        foreach ($children[$resource] ?? [] as $name => $child) {
            $chains += $this->chains($child, "$chain->$name()", $children);
        }

        return $chains;
    }

    private function parameter(Parameter $parameter): string
    {
        $declared = (string) $parameter->getType();
        $type = $declared === '' ? '' : implode('|', array_map(fn (string $part) => (str_starts_with($part, '?') ? '?' : '').class_basename(ltrim($part, '?')), explode('|', $declared)));
        $type = $parameter->isNullable() && $type !== '' && ! str_contains($type, '|') && ! str_contains($type, 'null') && ! str_starts_with($type, '?') && $type !== 'mixed' ? "?$type" : $type;
        $default = $parameter->hasDefaultValue() ? ' = '.($parameter->getDefaultValue() === null ? 'null' : var_export($parameter->getDefaultValue(), true)) : '';

        return ($type === '' ? '' : "$type ").'$'.$parameter->getName().$default;
    }

    private function returns(Method $method): string
    {
        $type = (string) $method->getReturnType();
        preg_match('/@return\\s+\\S*Collection<int, \\\\?([\\w\\\\]+)>/', $method->getComment() ?? '', $item);

        return match (true) {
            $type === 'mixed' => 'iSAMS\'s JSON, decoded (the spec gives no model)',
            isset($item[1]) => '`'.class_basename($type).'<'.class_basename($item[1]).'>`',
            default => '`'.($method->isReturnNullable() || str_starts_with($type, '?') ? '?' : '').class_basename(ltrim($type, '?')).'`',
        };
    }
}
